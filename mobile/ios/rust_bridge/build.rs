use std::{
    env,
    fmt::Write,
    fs,
    path::{Path, PathBuf},
};

use anki_proto_gen::get_services;
use anyhow::{Context, Result};
use inflections::Inflect;
use prost_reflect::DescriptorPool;

fn main() -> Result<()> {
    let descriptors = PathBuf::from(
        env::var("DESCRIPTORS_BIN").context("DESCRIPTORS_BIN must point at Anki descriptors")?,
    );
    println!("cargo:rerun-if-changed={}", descriptors.display());

    let generated = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../BrainliftMobile/Backend/Generated/BackendMethods.swift");
    let pool = DescriptorPool::decode(fs::read(&descriptors)?.as_slice())?;
    let (_, services) = get_services(&pool);

    let mut swift = String::from(
        "// @generated by mobile/ios/rust_bridge/build.rs; do not edit.\n\
         import Foundation\n\n\
         struct BackendMethodAddress: Sendable, Equatable {\n\
         \tlet service: UInt32\n\
         \tlet method: UInt32\n\
         }\n\n\
         enum BackendMethods {\n",
    );
    for service in services {
        for method in service.all_methods() {
            let name = format!("{} {}", service.name, method.name).to_camel_case();
            writeln!(
                swift,
                "\tstatic let {name} = BackendMethodAddress(service: {}, method: {})",
                service.index, method.index
            )?;
        }
    }
    swift.push_str("}\n");

    fs::create_dir_all(generated.parent().context("generated path has no parent")?)?;
    write_if_changed(&generated, swift.as_bytes())?;
    Ok(())
}

fn write_if_changed(path: &Path, content: &[u8]) -> Result<()> {
    if fs::read(path).ok().as_deref() != Some(content) {
        fs::write(path, content)?;
    }
    Ok(())
}
